"""Behavioural diff: the native Rust fight (mw-play logs) against the recompiled-core oracle observations.

python -I tools/pl0000/oracle_compare.py
Oracle: evidence/*feedback-observations.jsonl (read-only samples of the original running on the recompiled core: actor
state bytes, current motion matched by content hash, motion step, HP). Native: evidence/native-play/{script,bot}-*.log.jsonl.
Frame-exact parity is not claimed (the oracle samples are not frame-atomic, the RNG seed and inputs differ); this
compares which motion each state plays, the motion step, and the HP steps that occur.
Writes research/ORACLE-COMPARE.md and research/oracle-compare.json.
"""
import collections, glob, json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def clip_name(m):
    for r in (m or {}).get('resourceMatches') or []:
        n = r.get('id', '').split('#')[-1].split('@')[0]
        if n: return n
    return None


def oracle():
    pairs = {'player': collections.Counter(), 'rin': collections.Counter()}
    steps = collections.defaultdict(set)
    hp = {'player': collections.Counter(), 'rin': collections.Counter()}
    files = sorted(glob.glob(str(ROOT / 'evidence/*feedback-observations.jsonl')))
    n = 0
    for f in files:
        last = {}
        for line in open(f, encoding='utf-8'):
            try: r = json.loads(line)
            except Exception: continue
            a = r.get('actors') or {}
            for who, mkey in (('player', 'playerNativeMotion'), ('rin', 'rinNativeMotion')):
                act = a.get(who); m = r.get(mkey)
                if not act: continue
                n += 1
                st = (act.get('stateBytes11a11d') or [None, None])[1]
                name = clip_name(m)
                if st is not None and name:
                    pairs[who][(st, name)] += 1
                    if m.get('step68') is not None: steps[(who, name)].add(round(m['step68'], 3))
                h = act.get('hp')
                if h is not None:
                    if who in last and h != last[who]: hp[who][h - last[who]] += 1
                    last[who] = h
    return pairs, steps, hp, len(files), n


def native():
    pairs = {'player': collections.Counter(), 'rin': collections.Counter()}
    steps = collections.defaultdict(set)
    hp = {'player': collections.Counter(), 'rin': collections.Counter()}
    files = sorted(glob.glob(str(ROOT / 'evidence/native-play/script-*.log.jsonl')) + glob.glob(str(ROOT / 'evidence/native-play/bot-*.log.jsonl')) + glob.glob(str(ROOT / 'evidence/native-play/keybot-*.log.jsonl')) + glob.glob(str(ROOT / 'evidence/native-play/sim-*.log.jsonl')))
    for f in files:
        last = {}
        for line in open(f, encoding='utf-8'):
            try: r = json.loads(line)
            except Exception: continue
            if 'rin' not in r or 'state' not in r: continue
            pairs['player'][(r['state'], r['clip'])] += 1
            steps[('player', r['clip'])].add(round(r.get('rate', 1.), 3))
            pairs['rin'][(r['rin']['state'], r['rin']['clip'])] += 1
            for who, h in (('player', r.get('hp')), ('rin', r['rin'].get('hp'))):
                if h is None: continue
                if who in last and h != last[who]: hp[who][h - last[who]] += 1
                last[who] = h
    return pairs, steps, hp, len(files)


def main():
    op, os_, oh, ofiles, nobs = oracle()
    np_, ns, nh, nfiles = native()
    out = {'oracleFiles': ofiles, 'oracleSamples': nobs, 'nativeLogs': nfiles, 'actors': {}}
    lines = ['# Native fight vs recompiled-core oracle (behavioural diff)', '',
             f'Oracle: {ofiles} observation files ({nobs} actor samples, read-only, not frame-atomic). Native: {nfiles} '
             '`mw-play` scripted logs. Generated by `tools/pl0000/oracle_compare.py`. Frame-exact parity is not claimed: '
             'inputs, timing and the runtime RNG seed differ between the runs.', '']
    for who in ('player', 'rin'):
        o_states = collections.defaultdict(set); n_states = collections.defaultdict(set)
        for (st, name) in op[who]: o_states[st].add(name)
        for (st, name) in np_[who]: n_states[st].add(name)
        rows = []
        matched = missing = 0
        for st in sorted(o_states):
            o = o_states[st]; nn = n_states.get(st, set())
            both = sorted(o & nn); only_o = sorted(o - nn)
            matched += len(both); missing += len(only_o)
            rows.append(dict(state=st, oracle=sorted(o), native=sorted(nn), shared=both, oracleOnly=only_o))
        extra = {st: sorted(v) for st, v in n_states.items() if st not in o_states}
        out['actors'][who] = dict(states=rows, nativeOnlyStates=extra, oracleHpSteps=dict(oh[who]), nativeHpSteps=dict(nh[who]))
        lines += [f'## {who}', '', f'State/motion pairs seen in the oracle: {matched + missing}; reproduced by the native '
                  f'runs: {matched}; not reproduced: {missing}.', '', '| state | oracle motions | native motions | not reproduced |', '|---|---|---|---|']
        for r in rows:
            lines.append(f"| {r['state']} | {', '.join(m.replace('.mot', '') for m in r['oracle'])} | "
                         f"{', '.join(m.replace('.mot', '') for m in r['native']) or '-'} | {', '.join(m.replace('.mot', '') for m in r['oracleOnly']) or '-'} |")
        lines += ['', f"States only in the native runs (not sampled in the oracle): {', '.join(str(k) for k in sorted(extra)) or 'none'}.", '',
                  f"HP steps, oracle: {dict(sorted(oh[who].items()))}; native: {dict(sorted(nh[who].items()))}.", '']
    step_rows = []
    for (who, name), vals in sorted(os_.items()):
        if (who, name) in ns: step_rows.append(f"| {who} | {name.replace('.mot', '')} | {sorted(vals)} | {sorted(ns[(who, name)])} |")
    lines += ['## Motion step (frames per game frame) where both ran the same motion', '', '| actor | motion | oracle | native |', '|---|---|---|---|'] + step_rows
    (ROOT / 'research/ORACLE-COMPARE.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    (ROOT / 'research/oracle-compare.json').write_text(json.dumps(out, indent=1, default=str), encoding='utf-8')
    for who in ('player', 'rin'):
        a = out['actors'][who]; print(who, 'oracle hp', a['oracleHpSteps'], 'native hp', a['nativeHpSteps'])


if __name__ == '__main__':
    main()
